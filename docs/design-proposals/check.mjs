import { writeFile } from 'node:fs/promises';

const tabs = await fetch('http://127.0.0.1:9333/json').then(r => r.json());
const tab = tabs.find(t => t.url.includes('propostas.html'));
if (!tab) throw new Error('Página de propostas não encontrada');
const socket = new WebSocket(tab.webSocketDebuggerUrl);
await new Promise(resolve => socket.addEventListener('open', resolve, { once: true }));
let id = 0;
const pending = new Map();
socket.addEventListener('message', e => {
  const message = JSON.parse(e.data);
  if (!message.id) return;
  const { resolve, reject } = pending.get(message.id);
  pending.delete(message.id);
  message.error ? reject(new Error(message.error.message)) : resolve(message.result);
});
const command = (method, params = {}) => new Promise((resolve, reject) => {
  pending.set(++id, { resolve, reject });
  socket.send(JSON.stringify({ id, method, params }));
});
const evaluate = async expression => {
  const result = await command('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true });
  if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails));
  return result.result.value;
};
const render = () => evaluate('new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)))');
const assert = async (expression, name) => {
  if (!await evaluate(expression)) throw new Error(name);
  console.log(`OK: ${name}`);
};
const capture = async path => {
  const { data } = await command('Page.captureScreenshot', { format: 'png', captureBeyondViewport: true });
  await writeFile(new URL(path, import.meta.url), Buffer.from(data, 'base64'));
};
